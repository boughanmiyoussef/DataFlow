import pandas as pd
import duckdb
import streamlit as st

st.set_page_config(
    page_title="Sales Pipeline Dashboard",
    page_icon="🛍️",
    layout="wide"
)

st.title("🛍️ Sales Pipeline Dashboard")
st.markdown("Real-time analytics powered by Airflow, Faker, and DuckDB.")

@st.cache_resource
def load_data_warehouse():
    csv_path = "/opt/airflow/data/raw_sales.csv"
    conn = duckdb.connect(database=':memory:')
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS sales AS 
        SELECT * FROM read_csv_auto('{csv_path}')
    """)
    return conn

try:
    conn = load_data_warehouse()
    df_sales = conn.execute("SELECT * FROM sales").fetchdf()

    total_orders = len(df_sales)

    total_revenue = 0
    revenue_col = None
    for col in df_sales.columns:
        col_lower = col.lower()
        if any(kw in col_lower for kw in ['total', 'amount', 'price', 'revenue', 'sum', 'cost', 'value', 'sale']):
            if 'id' not in col_lower and 'qty' not in col_lower and 'quantity' not in col_lower:
                try:
                    val = pd.to_numeric(df_sales[col], errors='coerce').sum()
                    if val > 0:
                        total_revenue = val
                        revenue_col = col
                        break
                except:
                    continue

    if total_revenue == 0:
        for col in df_sales.select_dtypes(include=['number']).columns:
            if 'id' not in col.lower() and 'year' not in col.lower():
                total_revenue = pd.to_numeric(df_sales[col], errors='coerce').sum()
                revenue_col = col
                break

    col1, col2 = st.columns(2)
    col1.metric("Total Orders", f"{total_orders:,}")
    col2.metric("Total Revenue", f"${total_revenue:,.2f}")

    if revenue_col:
        st.caption(f"💡 Revenue derived from column: `{revenue_col}`")

    st.markdown("---")

    st.subheader("📊 Sales Analytics & Trends")

    date_col = next((c for c in df_sales.columns if any(d in c.lower() for d in ['date', 'time', 'created'])), None)
    if date_col and revenue_col:
        try:
            st.markdown("### 📈 Revenue Trend Over Time")
            df_time = df_sales.copy()
            df_time[date_col] = pd.to_datetime(df_time[date_col], errors='coerce')
            df_time['clean_revenue'] = pd.to_numeric(df_time[revenue_col], errors='coerce')
            
            chart_data = df_time.groupby(df_time[date_col].dt.date)['clean_revenue'].sum().reset_index()
            chart_data.columns = ['Date', 'Revenue']
            chart_data = chart_data.dropna().sort_values('Date')
            
            st.line_chart(chart_data.set_index('Date'))
        except Exception:
            pass

    cat_col = next((c for c in df_sales.columns if any(cat in c.lower() for cat in ['category', 'product', 'department', 'region', 'city', 'item'])), None)
    if cat_col and revenue_col:
        try:
            st.markdown(f"### 🏷️ Top Revenue by {cat_col.replace('_', ' ').title()}")
            df_cat = df_sales.copy()
            df_cat['clean_revenue'] = pd.to_numeric(df_cat[revenue_col], errors='coerce')
            
            bar_data = df_cat.groupby(cat_col)['clean_revenue'].sum().reset_index()
            bar_data.columns = [cat_col.replace('_', ' ').title(), 'Revenue']
            bar_data = bar_data.sort_values('Revenue', ascending=False).head(10)
            
            st.bar_chart(bar_data.set_index(bar_data.columns[0]))
        except Exception:
            pass

    # Expandable debug view
    with st.expander("🔍 View Detected Columns & Debug Info"):
        st.write("Columns found in CSV:", df_sales.columns.tolist())
        st.dataframe(df_sales.head(3))

    st.markdown("---")
    st.subheader("📋 Recent Sales Transactions")
    st.dataframe(df_sales, use_container_width=True)

except Exception as e:
    st.warning("⚠️ Waiting for `raw_sales.csv` to be generated by Airflow...")
    st.expander("Show technical error details").write(e)